-- 리뷰 숨기기(2026-11-14 사용자, 관리자 마이페이지 1 — docs/03_admin.md 1-6). 신발 숨김(V8)과 같은 방식이다.
-- 관리자가 리뷰를 숨기면 행은 지우지 않고 hidden_at 을 적는다. 영구 삭제는 숨긴 리뷰에서만 따로 한다(앱이 막는다).
--   hidden_at  숨긴 때(UTC). NULL 이면 보인다. 기존 행은 모두 NULL(보인다) — 추측해 채우지 않는다
-- 숨긴 리뷰가 빠지는 곳(앱): 공개 리뷰 목록 · 단건(/api/reviews — 챗봇 색인도 이것을 읽는다), 신발의 평점 · 리뷰 수(다시 센다),
--   요약 입력과 다시 만들지 판단할 때의 리뷰 수, 「도움이 돼요」 누르기. 숨긴 리뷰의 도움이 돼요 · 실사용 후기 행은 DB 에 남는다
-- 누가 숨겼는지는 활동 기록(admin.review.hide)에 남긴다 — 신발 숨김(V8)처럼 칸을 두지 않는다
-- 열 추가는 맨 뒤라 MySQL 8 INSTANT — 테이블을 다시 만들지 않는다. 옛 이미지(ddl-auto validate)는 모르는 열을 보지 않는다.
--   옛 이미지로 롤백하면 숨긴 리뷰가 다시 보이고 평점에도 다시 들어간다(지워지지는 않는다 — 런북)

ALTER TABLE reviews
  ADD COLUMN hidden_at DATETIME(3) NULL;
