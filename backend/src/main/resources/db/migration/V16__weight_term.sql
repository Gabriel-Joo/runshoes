-- 무게 용어(terms key 'weight') 설명을 환산 규칙(01a_catalog_sources.md 1-3a — 반 사이즈당 약 2.6%)에 맞춘다(2026-11-10 사용자).
-- 옛 설명의 "10mm 커질 때마다 5~10g"은 270mm 로 맞춘 무게(V15)와 다른 숫자를 말했다 — 툴팁이 사이트의 진실의 원천이고
-- 챗봇이 용어 사전을 그대로 프롬프트에 넣는다(09_chatbot_rag.md 8절).
-- "240g · 300g"은 업계 통념이다(공식 기준 아님) — "통상적으로"로 비교하기 배지(이 사이트 281켤레의 25% · 75%)와 다른 기준임을 밝힌다.
-- id 가 아니라 term_key 로 고친다 — id 12 가 둘(weight · outsole, 시드 그대로 — 고치지 않는다).
-- V15(DDL)와 목적이 달라 나눴다(한 마이그레이션에 한 목적). 운영에는 같은 이미지 · 같은 Sync 로 함께 들어간다.

-- ---------------------------------------------------------------------------------------------
-- 0. 가드 — 맨 첫 구문. 무게 설명이 시드(V2) 원문 그대로인 행이 정확히 하나일 때만 진행한다.
--    누가 먼저 고쳤으면 ERROR 1242(Subquery returns more than 1 row)로 멈추고 아무것도 바꾸지 않는다.
-- ---------------------------------------------------------------------------------------------
SELECT IF(
  (SELECT COUNT(*) FROM terms WHERE term_key = 'weight') = 1
  AND (SELECT COUNT(*) FROM terms WHERE term_key = 'weight' AND description =
        '신발 한 짝의 무게입니다. 브랜드가 정한 대표 사이즈(보통 270~280mm) 기준으로 표기하기 때문에, 실제 신는 사이즈에 따라 달라집니다. 사이즈가 10mm 커질 때마다 5~10g 정도 늘어납니다. 220g 이하면 가벼운 편, 300g 이상이면 무거운 편입니다.') = 1,
  'v16 guard ok',
  (SELECT 'v16 guard: weight term differs from seed' UNION ALL SELECT 'v16 guard: weight term differs from seed')
) AS v16_guard;

-- ---------------------------------------------------------------------------------------------
-- 1. 설명 바꾸기 — name · short 는 그대로
-- ---------------------------------------------------------------------------------------------
UPDATE terms
   SET description = '신발 한 짝의 무게입니다. 브랜드가 정한 대표 사이즈(대부분 270mm) 기준으로 표기하기 때문에, 실제 신는 사이즈에 따라 달라집니다. 사이즈가 5mm(반 치수) 커질 때마다 약 2.6% 정도 무거워집니다. 비교하기 페이지에서는 신발 무게를 비교할 때 270mm로 환산한 값을 씁니다. 통상적으로 240g 이하면 가벼운 편이고, 300g 이상이면 무거운 편입니다.'
 WHERE term_key = 'weight';
